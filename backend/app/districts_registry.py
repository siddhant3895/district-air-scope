DISTRICT_MAP: Dict[str, DistrictRegistryEntry] = {
    entry.district.id: entry for entry in TARGET_DISTRICTS
}


def _normalize_name(name: str) -> str:
    return re.sub(r"\s+", " ", name.strip().lower())


STATION_BY_EXTERNAL_ID: Dict[str, StationRecord] = {
    _normalize_name(s.external_station_id): s for s in REVIEWED_STATIONS
}

STATION_BY_ID: Dict[str, StationRecord] = {
    s.station_id: s for s in REVIEWED_STATIONS
}


def list_target_districts() -> List[District]:
    return [entry.district for entry in TARGET_DISTRICTS]


def get_district_mapping(district_id: str) -> Optional[DistrictRegistryEntry]:
    return DISTRICT_MAP.get(district_id)


def list_verified_stations_for_district(district_id: str) -> List[StationRecord]:
    return [
        s for s in REVIEWED_STATIONS if s.district_id == district_id and s.is_verified_member
    ]


def resolve_reviewed_station(external_station_name: str) -> Optional[StationRecord]:
    """Look up a station in the reviewed registry by its exact CPCB station name or canonical prefix."""
    norm = _normalize_name(external_station_name)
    if norm in STATION_BY_EXTERNAL_ID:
        return STATION_BY_EXTERNAL_ID[norm]

    # Secondary check against reviewed station_name + city when agency suffix varies slightly
    for station in REVIEWED_STATIONS:
        prefix = _normalize_name(f"{station.station_name}, {station.city}")
        if norm.startswith(prefix):
            return station
    return None
